#!/usr/bin/env python3
"""Render portable agent-guidance files from shared project fragments.

Codex AGENTS.md has no documented in-file include mechanism, so its shared
content is materialized.  Claude Code has a native project-local import, so
CLAUDE.md is a small wrapper around the same canonical fragments.  The
renderer owns only ANR:PROJECT-GUIDANCE blocks.  Existing OMX marker blocks
are validated and preserved byte-for-byte outside that block.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import os
from pathlib import Path
import re
import sys
import tempfile
from typing import Sequence


PROJECT_START = "<!-- ANR:PROJECT-GUIDANCE:START -->"
PROJECT_END = "<!-- ANR:PROJECT-GUIDANCE:END -->"
OMX_MARKER = re.compile(r"<!--\s*(OMX:[A-Za-z0-9:_-]+):(START|END)\s*-->")
GENERATED_NOTICE = "<!-- Generated by scripts/generate_agent_guidance.py; edit agent_guidance/, not this block. -->"


@dataclass(frozen=True)
class GuidanceTarget:
    relative_path: str
    tool_fragment: str
    native_claude_includes: bool = False
    initial_prefix: str = ""


TARGETS = (
    GuidanceTarget("AGENTS.md", "codex.md"),
    GuidanceTarget("CLAUDE.md", "claude.md", native_claude_includes=True),
    GuidanceTarget("GEMINI.md", "gemini.md"),
    GuidanceTarget("CODEBUDDY.md", "codebuddy.md"),
    GuidanceTarget("HERMES.md", "hermes.md"),
    GuidanceTarget(
        ".cursor/rules/project.mdc",
        "cursor.md",
        initial_prefix="---\ndescription: ANR evidence extraction and analysis pipeline — project layout, workflows, and conventions\nglobs: **/*\nalwaysApply: true\n---\n\n",
    ),
)


class GuidanceError(ValueError):
    """A source/output contract failure that must not rewrite guidance."""


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="project root containing agent_guidance/ (default: repository root)",
    )
    parser.add_argument("--check", action="store_true", help="fail if outputs are not current; do not write")
    return parser.parse_args(argv)


def _read_regular_file(path: Path) -> str:
    if path.is_symlink():
        raise GuidanceError(f"refusing symlink source: {path}")
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError as error:
        raise GuidanceError(f"missing guidance source: {path}") from error


def _assert_no_symlink_path(root: Path, target: Path) -> None:
    try:
        relative = target.relative_to(root)
    except ValueError as error:
        raise GuidanceError(f"target escapes root: {target}") from error
    current = root
    if current.is_symlink():
        raise GuidanceError(f"refusing symlink root: {root}")
    for component in relative.parts:
        current = current / component
        if current.is_symlink():
            raise GuidanceError(f"refusing symlink target path: {current}")


def _validate_omx_blocks(content: str, path: Path) -> None:
    stack: list[str] = []
    for match in OMX_MARKER.finditer(content):
        name, phase = match.groups()
        if phase == "START":
            stack.append(name)
            continue
        if not stack:
            raise GuidanceError(f"unmatched OMX end marker in {path}: {name}")
        active = stack.pop()
        if active != name:
            raise GuidanceError(
                f"misnested OMX marker in {path}: expected {active}:END, got {name}:END"
            )
    if stack:
        raise GuidanceError(f"unclosed OMX marker in {path}: {stack[-1]}")


def _managed_bounds(content: str, path: Path) -> tuple[int, int] | None:
    starts = [match.start() for match in re.finditer(re.escape(PROJECT_START), content)]
    ends = [match.start() for match in re.finditer(re.escape(PROJECT_END), content)]
    if not starts and not ends:
        return None
    if len(starts) != 1 or len(ends) != 1 or starts[0] >= ends[0]:
        raise GuidanceError(f"malformed managed guidance markers in {path}")
    return starts[0], ends[0] + len(PROJECT_END)


def _managed_block(root: Path, target: GuidanceTarget) -> str:
    common = _read_regular_file(root / "agent_guidance" / "project.md").strip()
    tool = _read_regular_file(root / "agent_guidance" / "tools" / target.tool_fragment).strip()
    if target.native_claude_includes:
        body = "\n".join((
            GENERATED_NOTICE,
            "@agent_guidance/project.md",
            "@agent_guidance/tools/claude.md",
        ))
    else:
        body = "\n\n".join((GENERATED_NOTICE, common, tool))
    return f"{PROJECT_START}\n{body}\n{PROJECT_END}"


def render_target(root: Path, target: GuidanceTarget) -> str:
    target_path = root / target.relative_path
    _assert_no_symlink_path(root, target_path)
    managed = _managed_block(root, target)
    if not target_path.exists():
        return target.initial_prefix + managed + "\n"

    existing = _read_regular_file(target_path)
    _validate_omx_blocks(existing, target_path)
    bounds = _managed_bounds(existing, target_path)
    if bounds is None:
        if OMX_MARKER.search(existing):
            raise GuidanceError(
                f"refusing to initialize OMX-marker-bearing legacy file without {PROJECT_START}: {target_path}"
            )
        return target.initial_prefix + managed + "\n"

    start, end = bounds
    return existing[:start] + managed + existing[end:]


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # The root-relative symlink check runs before this helper.  Write in the
    # destination directory and replace atomically so partial guidance files
    # cannot become committed outputs.
    fd, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
            handle.write(content)
        os.replace(temporary, path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def run(root: Path, *, check: bool) -> int:
    root = root.resolve()
    if not root.is_dir():
        raise GuidanceError(f"root is not a directory: {root}")
    rendered: list[tuple[Path, str]] = []
    for target in TARGETS:
        target_path = root / target.relative_path
        rendered.append((target_path, render_target(root, target)))

    stale = [path for path, content in rendered if not path.exists() or path.read_text(encoding="utf-8") != content]
    if check:
        if stale:
            for path in stale:
                print(f"out of date: {path.relative_to(root)}", file=sys.stderr)
            return 1
        return 0

    for path, content in rendered:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            _atomic_write(path, content)
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        return run(args.root, check=args.check)
    except GuidanceError as error:
        print(f"agent guidance generation failed: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
